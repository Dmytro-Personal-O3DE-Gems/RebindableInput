    RebindableInputComponent::RebindableInputComponent()
        : m_uuid{ AZ::Uuid::CreateRandom() }
    {
    }

    RebindableInputComponent::~RebindableInputComponent() = default;

    void RebindableInputComponent::GetProvidedServices(AZ::ComponentDescriptor::DependencyArrayType& provided)
    {
        // The same service as StartingPointInput's Input component, so components that require it keep working.
        provided.push_back(AZ_CRC_CE("InputConfigurationService"));
    }

    void RebindableInputComponent::GetIncompatibleServices(AZ::ComponentDescriptor::DependencyArrayType& incompatible)
    {
        // Only one input configuration per entity: two of them would send every event twice.
        incompatible.push_back(AZ_CRC_CE("InputConfigurationService"));
    }

    void RebindableInputComponent::Reflect(AZ::ReflectContext* reflection)
    {
        AZ::SerializeContext* serializeContext = azrtti_cast<AZ::SerializeContext*>(reflection);
        if (serializeContext)
        {
            serializeContext->Class<RebindableInputComponent, AZ::Component>()
                ->Version(1)
                ->Field("Input Event Bindings", &RebindableInputComponent::m_inputEventBindingsAsset)
                ->Field("Local Player Index", &RebindableInputComponent::m_localPlayerIndex)
            ;

            AZ::EditContext* editContext = serializeContext->GetEditContext();
            if (editContext)
            {
                editContext->Class<RebindableInputComponent>("Rebindable Input",
                    "Binds a set of inputs to events by referencing a .keybinds file. Works like the Input component, "
                    "and the bindings can be changed at runtime")
                    ->ClassElement(AZ::Edit::ClassElements::EditorData, "")
                        ->Attribute(AZ::Edit::Attributes::Category, "Gameplay")
                        // The icons come from StartingPointInput's Assets folder (this gem depends on it).
                        ->Attribute(AZ::Edit::Attributes::Icon, "Editor/Icons/Components/InputConfig.svg")
                        ->Attribute(AZ::Edit::Attributes::ViewportIcon, "Editor/Icons/Components/Viewport/InputConfig.svg")
                        ->Attribute(AZ::Edit::Attributes::PrimaryAssetType, AZ::AzTypeInfo<InputEventBindingsAsset>::Uuid())
                        ->Attribute(AZ::Edit::Attributes::AppearsInAddComponentMenu, AZ_CRC_CE("Game"))
                        ->Attribute(AZ::Edit::Attributes::HelpPageURL, "https://www.o3de.org/docs/user-guide/components/reference/gameplay/input/")
                    ->DataElement(AZ::Edit::UIHandlers::Default, &RebindableInputComponent::m_inputEventBindingsAsset, "Input to event bindings",
                    "Asset containing input to event binding information.")
                        ->Attribute(AZ::Edit::Attributes::AutoExpand, true)
                        ->Attribute(AZ::Edit::Attributes::ContainerCanBeModified, true)
                        ->Attribute("BrowseIcon", ":/stylesheet/img/UI20/browse-edit-select-files.svg")
                        ->Attribute("EditButton", "")
                        ->Attribute("EditDescription", "Open in Asset Editor")
                        ->Attribute("ComponentIdentifier", &RebindableInputComponent::m_uuid)
                    ->DataElement(AZ::Edit::UIHandlers::SpinBox, &RebindableInputComponent::m_localPlayerIndex, "Local player index",
                            "The player index that this component will receive input from (0 based, -1 means all controllers).\n"
                            "Will only work on platforms such as PC where the local user id corresponds to the local player index.\n"
                            "For other platforms, SetLocalUserId must be called at runtime with the id of a logged in user.")
                        ->Attribute(AZ::Edit::Attributes::Min, -1)
                        ->Attribute(AZ::Edit::Attributes::Max, 3)
                    ;
            }
        }
    }

    void RebindableInputComponent::Init()
    {
        // The player index that this component will receive input from (0 based, -1 means all controllers)
        // can be set from data, but will only work on platforms such as PC where the local user id corresponds
        // to the local player index. For other platforms, SetLocalUserId must be called at runtime with the id
        // of a logged in user, which will overwrite anything set here from data.
        if (m_localPlayerIndex == -1)
        {
            m_localUserId = AzFramework::LocalUserIdAny;
        }
        else
        {
            // we have to cast to u32 here even if LocalUserId is not a u32 type because some platforms use
            // an aggregate type for m_localUserId and only have the pertinent constructors/operators for u32
            m_localUserId = aznumeric_cast<AZ::u32>(m_localPlayerIndex);
        }
    }

    void RebindableInputComponent::Activate()
    {
        StartingPointInput::InputConfigurationComponentRequestBus::Handler::BusConnect(GetEntityId());
        AZ::Data::AssetBus::Handler::BusConnect(m_inputEventBindingsAsset.GetId());
    }

    void RebindableInputComponent::Deactivate()
    {
        StartingPointInput::InputConfigurationComponentRequestBus::Handler::BusDisconnect();
        AZ::Data::AssetBus::Handler::BusDisconnect();
        if (BindingsRegistryRequests* registry = GetBindingsRegistry())
        {
            registry->RemoveBindings(GetEntityId());
        }
    }

    void RebindableInputComponent::SetLocalUserId(AzFramework::LocalUserId localUserId)
    {
        if (m_localUserId != localUserId)
        {
            // Kept here as well: it is passed with SetBindings when the asset becomes ready.
            m_localUserId = localUserId;
            if (BindingsRegistryRequests* registry = GetBindingsRegistry())
            {
                registry->SetLocalUserId(GetEntityId(), m_localUserId);
            }
        }
    }

    void RebindableInputComponent::OnAssetReloaded(AZ::Data::Asset<AZ::Data::AssetData> asset)
    {
        if (asset.GetId() == m_inputEventBindingsAsset.GetId())
        {
            m_inputEventBindingsAsset = asset;
            if (asset.IsReady())
            {
                // SetBindings replaces the old bindings, so they do not double up.
                OnAssetReady(asset);
            }
            else if (BindingsRegistryRequests* registry = GetBindingsRegistry())
            {
                // Like the original component: the old bindings are turned off until the new data is ready.
                registry->RemoveBindings(GetEntityId());
            }
        }
    }

    void RebindableInputComponent::OnAssetReady(AZ::Data::Asset<AZ::Data::AssetData> asset)
    {
        if (asset.GetAs<InputEventBindingsAsset>())
        {
            m_inputEventBindingsAsset = asset;

            // The system component clones the bindings, activates them and owns the clone.
            if (BindingsRegistryRequests* registry = GetBindingsRegistry())
            {
                registry->SetBindings(GetEntityId(), m_inputEventBindingsAsset, m_localUserId);
            }
        }
        else
        {
            AZ_Error("RebindableInput", false, "Input bindings asset is not the correct type.");
        }
    }

    BindingsRegistryRequests* RebindableInputComponent::GetBindingsRegistry() const
    {
        BindingsRegistryRequests* registry = BindingsRegistryInterface::Get();
        AZ_Error("RebindableInput", registry != nullptr,
            "Entity %s: RebindableInputSystemComponent is not available, the input bindings of this entity do not work.",
            GetEntityId().ToString().c_str());
        return registry;
    }

    void RebindableInputComponent::EditorSetPrimaryAsset(const AZ::Data::AssetId& assetId)
    {
        m_inputEventBindingsAsset.Create(assetId);
    }
